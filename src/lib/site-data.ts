/** Склонение слова «этаж» для характеристики этажности. */
function floorWord(n: number): string {
  if (n % 10 === 1 && n % 100 !== 11) return "этаж";
  if (n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14)) return "этажа";
  return "этажей";
}

/** Объединяет прилагательное и существительное с корректным пробелом. */
function join(adj: string, noun: string): string {
  return adj ? `${adj} ${noun}` : noun;
}

